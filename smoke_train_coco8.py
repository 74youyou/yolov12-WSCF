# -*- coding: utf-8 -*-
"""
coco8 冒烟训练脚本：用 8 张图的迷你数据集跑 1 个 epoch，验证整套训练管线。

运行方式（在仓库根目录）:
    conda activate yolov12
    python smoke_train_coco8.py

说明:
    - device=0 表示使用第一块 GPU（框架内部自动把模型与张量迁移到 GPU，
      无需手动 .cuda()）；训练启动后可另开终端用 nvidia-smi 查看显存占用验证。
"""
from ultralytics import YOLO  # Ultralytics 统一入口类

# ---------------------------------------------------------------------------
# 可调参数集中区
# ---------------------------------------------------------------------------
EPOCHS = 1      # 冒烟训练只跑 1 个 epoch（约几分钟），目的仅验证流程
IMGSZ = 640     # 输入尺寸
BATCH = 4       # 小批次即可
WORKERS = 2     # 数据加载子进程数
DEVICE = 0      # GPU 编号（0 = 第一块显卡）


def main():
    # -----------------------------------------------------------------------
    # 1. 构建 CSF 模型（与正式训练完全相同的结构定义）
    # -----------------------------------------------------------------------
    model = YOLO("ultralytics/cfg/models/v12/yolov12-csf.yaml")

    # -----------------------------------------------------------------------
    # 2. 加载官方预训练权重（验证权重映射逻辑；正式训练同样先 load 再 train）
    # -----------------------------------------------------------------------
    model.load("yolov12n.pt")

    # -----------------------------------------------------------------------
    # 3. 冒烟训练：coco8 数据集（内置 8 张图），1 个 epoch 验证
    #    数据加载 / 增强 / 前向 / 损失计算 / 反向传播 / 验证 全链路是否正常。
    #    plots=False 不生成图表，加快速度。
    # -----------------------------------------------------------------------
    model.train(
        data="coco8.yaml",   # ultralytics 内置微型数据集，无需联网下载（自带）
        epochs=EPOCHS,
        imgsz=IMGSZ,
        batch=BATCH,
        workers=WORKERS,
        device=DEVICE,
        plots=False,
    )
    # 若此脚本无报错跑完，说明环境就绪，可执行 train/train_stageA.py 正式训练


# ---------------------------------------------------------------------------
# Windows 下多进程数据加载要求入口函数放在 __main__ 保护下，避免递归启动
# ---------------------------------------------------------------------------
if __name__ == "__main__":
    main()